test('open read severity depends on personal columns', () => {
  const dir = path.join(tmp, 'catalog');
  migration(dir, '001.sql', `
    create table public.products (id int, name text, price numeric);
    alter table public.products enable row level security;
    create policy "public" on public.products for select using (true);
    create table public.people (id int, email text);
    alter table public.people enable row level security;
    create policy "public" on public.people for select using (true);`);
  const r = audit(dir);
  const sev = Object.fromEntries(r.leads.filter((l) => l.rule === 'RLS-POL-001').map((l) => [l.object, l.severity_hint]));
  assert.deepStrictEqual(sev, { 'public.products': 'medium', 'public.people': 'high' });
});

test('monorepo: each Supabase project is replayed on its own', () => {
  const dir = path.join(tmp, 'mono');
  migration(path.join(dir, 'apps', 'shop'), '001.sql', 'create table public.items (id int);');
  migration(path.join(dir, 'apps', 'blog'), '001.sql', 'create table public.items (id int);\nalter table public.items enable row level security;\ncreate policy "r" on public.items for select to authenticated using ((select auth.uid()) is null);');
  const r = audit(dir);
  assert.strictEqual(r.model.projects, 2);
  const noRls = r.leads.filter((l) => l.rule === 'RLS-TBL-001');
  assert.strictEqual(noRls.length, 1);
  assert.ok(noRls[0].file.startsWith('apps/shop/'));
});

