test('rls-ignore suppresses a reviewed statement', () => {
  const dir = path.join(tmp, 'ignore');
  migration(dir, '001.sql', `
    create table public.products (id int, name text);
    alter table public.products enable row level security;
    create policy "catalogue" on public.products for select using (true); -- rls-ignore: RLS-POL-001 public catalogue
  `);
  // a trailing comment belongs to the next statement; put it inside to attach it
  migration(dir, '002.sql', `create policy "catalogue2" on public.products for select -- rls-ignore: RLS-POL-001 public catalogue
    using (true);`);
  const r = audit(dir);
  assert.strictEqual(r.leads.filter((l) => l.rule === 'RLS-POL-001').length, 1);
});

